// Generates the Shopify custom pixel code from its template and the reviewed variant allowlist.
//   node scripts/build-checkout-pixel.mjs          write shopify/custom-pixels/*.live.js and *.diagnostic.js
//   node scripts/build-checkout-pixel.mjs --check  fail if the committed copies are out of date
import fs from "node:fs";

const dir = new URL("../shopify/custom-pixels/", import.meta.url);
const read = name => fs.readFileSync(new URL(name, dir), "utf8");

export function pixelConfig(eligibility, mode) {
  if (!/^\d{5,20}$/.test(eligibility.pixelId || "")) throw new Error("pixelId must be the numeric Meta dataset ID");
  if (mode !== "live" && mode !== "diagnostic") throw new Error("mode must be live or diagnostic");
  const ids = Object.keys(eligibility.variants || {});
  if (!ids.length) throw new Error("no eligible variants");
  for (const id of ids) {
    if (!/^\d{1,20}$/.test(id)) throw new Error(`variant ${id} is not a numeric Shopify variant ID`);
    if (Object.hasOwn(eligibility.neverEligible || {}, id)) throw new Error(`variant ${id} is listed as never eligible`);
  }
  return {pixelId: eligibility.pixelId, mode, variants: Object.fromEntries(ids.sort().map(id => [id, true]))};
}

export function buildPixel(template, eligibility, mode) {
  const marker = "/*__IQON_PIXEL_CONFIG__*/{}";
  if (template.split(marker).length !== 2) throw new Error("template must contain the config marker exactly once");
  const header = `// GENERATED by scripts/build-checkout-pixel.mjs (${mode}) — do not edit; paste as-is.\n`;
  return header + template.replace(marker, JSON.stringify(pixelConfig(eligibility, mode)));
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const template = read("iqon-meta-checkout.template.js");
  const eligibility = JSON.parse(read("eligibility.json"));
  let stale = 0;
  for (const mode of ["live", "diagnostic"]) {
    const name = `iqon-meta-checkout.${mode}.js`;
    const output = buildPixel(template, eligibility, mode);
    if (process.argv.includes("--check")) {
      const current = fs.existsSync(new URL(name, dir)) ? read(name) : "";
      if (current !== output) { console.error(`${name} is out of date`); stale++; }
    } else fs.writeFileSync(new URL(name, dir), output);
  }
  if (stale) process.exit(1);
}
